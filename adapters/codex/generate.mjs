export const CONFIG_HEADER = '# generated by workflow: node <plugin>/bin/adapter.mjs codex; do not edit, regenerate (P-017)';
export const AGENTS_BEGIN = '<!-- workflow:begin -->';
export const AGENTS_END = '<!-- workflow:end -->';
export const PERMISSION_PROFILE = 'workflow';
/** Events whose Codex input/output differs from Claude Code and go through adapters/codex/hook.mjs. */
export const TRANSLATED_EVENTS = { SessionStart: 'session-start', PreToolUse: 'pre-tool-use', Stop: 'stop' };
/** Claude Code events Codex does not have (hooks docs list 12 events; failed Bash arrives as PostToolUse). */
export const UNSUPPORTED_EVENTS = ['PostToolUseFailure'];
export const LOCAL_FILES = ['.codex/hooks.json', harnessSkills('codex').gitignore];

/** Compaction prompt (P-026): the summary is a state, not a history. */
export const COMPACT_PROMPT = [
  'Zhrň kontext ako stav práce, nie ako históriu rozhovoru. Presne tieto časti, každá najviac 3 riadky:',
  '1. Zadanie a téma (ID témy, ak existuje).',
  '2. Hotové (overené výsledky, nie zámery).',
  '3. Ďalší krok (jeden, konkrétny).',
  '4. Otvorené otázky a čakajúce správy.',
  '5. Dotknuté súbory.',
  'Po kompakcii je primárnym podkladom handover témy z brain, ktorý vloží hook SessionStart; nezhrňuj pravidlá workflow.',
].join('\n');

/** Pure function: policy + brain relative path -> .codex/config.toml as an object (serialized by toToml). */
export function codexConfig(policy, brainRel) {
  const filesystem = {};
  for (const p of policy.harness?.deny_paths || []) {
    // UNVERIFIED: whether a path relative to the project root (`../<brain>/**`) and `~` are accepted as
    // permissions.<profile>.filesystem keys; the docs show absolute paths and `:workspace_roots` sub-paths.
    // Absolute paths cannot be committed (P-004). The PreToolUse hook denies brain writes deterministically as the backup.
    for (const e of expandBrainPath(p, brainRel)) filesystem[e] = 'deny';
  }
  filesystem[':workspace_roots'] = { [`${harnessSkills('codex').gitignore}**`]: 'deny' };
  return {
    // P-026: compaction window from policy; compact_prompt shapes the summary as a state.
    model_auto_compact_token_limit: policy.compaction?.auto_compact_window_tokens ?? 200000,
    compact_prompt: COMPACT_PROMPT,
    // P-015: deny paths as a permission profile. UNVERIFIED: `default_permissions` must not be combined with a
    // user-level `sandbox_mode`; `extends = ":workspace"` is expected to keep workspace-write for the project.
    default_permissions: PERMISSION_PROFILE,
    features: {
      hooks: true, // on by default per docs; explicit so a user-level `hooks = false` does not win silently
      memories: policy.harness?.native_memory === true, // P-014: native memory off
    },
    permissions: { [PERMISSION_PROFILE]: { extends: ':workspace', filesystem } },
  };
}

/** Pure function: hooks/hooks.json -> .codex/hooks.json. Contains the absolute plugin path: local file, never committed. */
export function codexHooks(pluginRoot = PLUGIN_ROOT) {
  const src = readJson(path.join(pluginRoot, 'hooks', 'hooks.json'));
  const root = toPosix(pluginRoot);
  const hooks = {};
  for (const [event, groups] of Object.entries(src.hooks)) {
    if (UNSUPPORTED_EVENTS.includes(event)) continue;
    hooks[event] = groups.map((g) => {
      const group = {};
      // Codex reports file edits as tool `apply_patch` (matchers Edit|Write also match it); shell is `Bash`.
      if (g.matcher) group.matcher = event === 'PreToolUse' ? `${g.matcher}|apply_patch` : g.matcher;
      group.hooks = g.hooks.map((h) => {
        const script = h.args[0].replace('${CLAUDE_PLUGIN_ROOT}/', '');
        // hooks.json has no `args` field in Codex: one command string, run with the session cwd (docs).
        const command = TRANSLATED_EVENTS[event]
          ? `node "${root}/adapters/codex/hook.mjs" ${TRANSLATED_EVENTS[event]}`
          : `node "${root}/${script}"`;
        const out = { type: 'command', command, timeout: h.timeout, statusMessage: `workflow ${event}` };
        // Boot context up to 15 000 chars must reach the model whole (P-021, P-022); default threshold is 2500 tokens.
        if (event === 'SessionStart') out.additionalContextLimit = 0;
        return out;
      });
      return group;
    });
  }
  return {
    description: 'Workflow hooks for Codex (P-017). Generated locally by adapter.mjs codex: contains the plugin clone path, kept out of git (P-004). Logic: <plugin>/hooks/*.mjs; format translation: <plugin>/adapters/codex/hook.mjs.',
    hooks,
  };
}

/** Pure function: assembled rules -> managed block of AGENTS.md (the Codex entry point for rules, P-017). */
export function agentsBlock(rulesText, brainRel) {
  const skillsDir = harnessSkills('codex').gitignore;
  return [
    AGENTS_BEGIN,
    '# Workflow (generovaný blok, P-017)',
    '',
    `Tento blok generuje \`node <plugin>/bin/adapter.mjs codex\`; neupravuj ho ručne, ďalšie generovanie ho prepíše. Zdroj pravidiel je repo workflow (\`rules/*.md\` a výnimky v brain).`,
    '',
    '## Ako workflow beží v Codexe',
    '',
    `- Hook SessionStart doplní stavový riadok \`thread <id> | topic <id> (<state>) | mail: <n>\`, indexy pamäte a rozhodnutí, otvorené témy a verziu \`workflow <sha>\`. Ak hlási \`AGENTS.md stale\`, spusti adaptér znova (mimo bežiacej session).`,
    `- Skilly workflow a skilly brain sú lokálne kópie v \`${skillsDir}\` (generované pri každom štarte; neupravuj ich tam). Skripty volaj presne tak, ako ich uvádza SKILL.md skillu.`,
    brainRel ? `- Brain je \`${brainRel}\`. Zápis doň ide iba cez skilly \`save\`, \`topic\`, \`done\`; priamy zápis je zakázaný (P-013, P-040).` : '- Projekt nemá vlastný brain (P-024): témy, pamäť a handover sú v brain persony, ktorá ho spravuje.',
    '- Identita vlákna je `WORKFLOW_THREAD_ID` (v T3 `T3CODE_THREAD_ID`); bez stabilného ID vlákno tému nezaberie (P-038).',
    '- Správa `assist` alebo `blocker` má lehotu (TTL); keď uplynie bez odpovede, budenie ťa zobudí (P-042): povýš ju na `blocker`, zruš, alebo sa spýtaj operátora (skill `comms`).',
    '- Potvrdenie nebezpečného kroku (P-018) Codex nevie vyžiadať: hook taký krok odmietne; cieľ najprv commitni (aby bol obnoviteľný z gitu), alebo krok vykoná operátor.',
    '- Subagentom nedávaj pravidlá workflow ani obsah brain (P-027); deleguj cez skill `delegate`.',
    '',
    '## Pravidlá',
    '',
    rulesText.trim(),
    AGENTS_END,
  ].join('\n');
}

/** Managed block from an existing AGENTS.md, or null. */
export function extractAgentsBlock(text) {
  const start = String(text || '').indexOf(AGENTS_BEGIN);
  const end = String(text || '').indexOf(AGENTS_END);
  if (start === -1 || end === -1 || end < start) return null;
  return text.slice(start, end + AGENTS_END.length);
}

/** Replace the managed block in an existing AGENTS.md, or append it; other content is preserved. */
export function mergeAgentsMd(existing, block) {
  const current = extractAgentsBlock(existing);
  if (current) return existing.replace(current, block);
  const base = String(existing || '').replace(/\s*$/, '');
  return (base ? `${base}\n\n` : '') + block + '\n';
}

export function generateCodex({ projectDir, brainRel: brainRelArg = null }) {
  const notes = [];
  const written = [];
  const { brainInfo, written: cfgWritten } = ensureWorkflowConfig(projectDir, brainRelArg);
  if (cfgWritten) written.push(WORKFLOW_CONFIG);
  const brainDir = brainInfo && !brainInfo.error ? brainInfo.brain : null;
  const hasBrain = brainExists(brainDir);
  // The composed policy of the project (D-0025), as the Claude Code adapter.
  const composed = projectPolicy({ projectDir, brainDir: hasBrain ? brainDir : null, domain: resolveDomain(projectDir) });
  const policy = composed.policy;
  const ignoredLine = policyIgnoredLine(composed.ignored);
  if (ignoredLine) notes.push(ignoredLine);

  // .codex/config.toml (committed). Whole file is generated; a foreign file is not merged (TOML tables cannot be
  // concatenated safely): other settings belong to the user config ~/.codex/config.toml.
  const configFile = path.join(projectDir, '.codex', 'config.toml');
  const existing = readText(configFile, null);
  if (existing !== null && !existing.startsWith(CONFIG_HEADER)) {
    throw new Error(`${toPosix(path.relative(projectDir, configFile))} exists and was not generated by workflow; move its settings to the user config (~/.codex/config.toml) and remove it, then run the adapter again (P-017)`);
  }
  const brainRel = brainInfo?.brainRel ?? null;
  const config = codexConfig(policy, brainRel);
  writeText(configFile, `${CONFIG_HEADER}\n${toToml(config)}`);
  written.push('.codex/config.toml');

  // .codex/hooks.json (local, gitignored: absolute plugin path).
  writeJson(path.join(projectDir, '.codex', 'hooks.json'), codexHooks(PLUGIN_ROOT));
  written.push('.codex/hooks.json (local)');

  // AGENTS.md (committed): rules assembled with the codex harness layer.
  const rules = assembleRules({ brainDir: hasBrain ? brainDir : null, policy, harness: 'codex', layers: composed.layers });
  if (rules.overLimit.length) notes.push(`limit: ${rules.overLimit.join('; ')} (P-022)`);
  if (rules.errors.length) notes.push(`refused exceptions: ${rules.errors.join('; ')}`);
  const agentsFile = path.join(projectDir, 'AGENTS.md');
  writeText(agentsFile, mergeAgentsMd(readText(agentsFile, ''), agentsBlock(rules.text, brainRel)));
  written.push('AGENTS.md');

  fs.mkdirSync(path.join(projectDir, 'local'), { recursive: true });
  fs.mkdirSync(path.join(projectDir, SCRATCH_DIR), { recursive: true });
  if (ensureGitignore(projectDir, [...LOCAL_FILES, 'local/', `${SCRATCH_DIR}/`])) written.push('.gitignore');
  if (hasBrain && brainInfo.persona) notes.push(commitPersonaFiles({ brainDir, policy, files: [WORKFLOW_CONFIG, '.codex/config.toml', 'AGENTS.md', '.gitignore'] }));

  // .agents/skills/ (local): workflow skills with the plugin path substituted + brain skills.
  const sync = syncBrainSkills({ projectDir, brainDir: hasBrain ? brainDir : null, harness: 'codex', repoSources: hasBrain ? adapterSkillSources(projectDir, brainDir) : [], domainBrainDir: composed.layers.projectBrain ? composed.layers.domainBrain : null });
  written.push(`${harnessSkills('codex').gitignore} (local)`);
  notes.push(`skills copied to ${harnessSkills('codex').gitignore}: ${sync.copied.join(', ')}`);
  if (!brainInfo) notes.push(NO_BRAIN_NOTE.replace('<harness>', 'codex'));
  else if (!hasBrain) notes.push(`brain not found at ${brainRel}; propose to the operator: node <plugin>/bin/brain-init.mjs ${brainRel} --project . (P-024)`);
  return { written, notes, config, brainRel, hasBrain };
}
